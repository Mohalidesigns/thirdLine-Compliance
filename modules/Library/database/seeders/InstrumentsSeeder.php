    public function run(): void
    {
        $data = $this->instrumentData();

        foreach ($data as $row) {
            $regulator = Regulator::where('code', $row['regulator'])->first();
            $type = InstrumentType::where('name', $row['type'])->first();
            $nature = Nature::where('name', $row['nature'])->first();
            $status = Status::where('name', $row['status'])->first();
            $area = AreaOfFocus::where('name', $row['area'])->first();
            $risk = RiskRating::where('name', $row['risk'])->first();

            if (! $regulator || ! $type || ! $nature || ! $status || ! $area || ! $risk) {
                continue;
            }

            Instrument::firstOrCreate(
                ['source_title' => $row['title']],
                [
                    'objectives' => $row['objectives'],
                    'date_issue' => $row['date_issue'],
                    'date_commence' => $row['date_commence'],
                    'regulator_id' => $regulator->id,
                    'instrument_type_id' => $type->id,
                    'nature_id' => $nature->id,
                    'status_id' => $status->id,
                    'area_of_focus_id' => $area->id,
                    'risk_rating_id' => $risk->id,
                    'applicability' => $row['applicability'] ?? 'Yes',
                    'risk_rating_explain' => $row['risk_explain'] ?? null,
                    'commercial_bank_relevance' => $row['bank_relevance'] ?? null,
                ]
            );
        }
    }

