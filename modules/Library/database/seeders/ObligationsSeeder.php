    public function run(): void
    {
        $instruments = Instrument::with('regulator')->get()->keyBy(fn ($i) => $i->source_title);

        $obligations = $this->obligationData();

        foreach ($obligations as $row) {
            $instrument = $instruments->get($row['instrument_title']);
            if ($instrument === null) {
                continue;
            }

            Obligation::firstOrCreate(
                [
                    'instrument_id' => $instrument->id,
                    'title' => $row['title'],
                ],
                [
                    'reference' => $row['reference'] ?? null,
                    'description' => $row['description'],
                    'due_basis' => $row['due_basis'],
                    'frequency' => $row['frequency'] ?? null,
                    'next_due_date' => $row['next_due_date'] ?? null,
                    'responsible_team' => $row['responsible_team'] ?? 'Compliance',
                    'status' => $row['status'] ?? 'open',
                ]
            );
        }
    }

